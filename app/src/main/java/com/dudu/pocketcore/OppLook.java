    /** v1 표의 세 색 — row 0~15(LookTab.row), sty, i 0~15 */
    static int[] tab(int row, int sty, int i) {
        short[] r = T1[row];
        int k = i <= 1 ? ((sty & 1) * 2 + i) * 3 : (4 + i - 2) * 3;
        return new int[]{ r[k], r[k + 1], r[k + 2] };
    }

    /** 세 색 채널 차 합(0~135) — native tdist · 생성기 colorgen.dist 와 같은 식 */
    static int dist(int[] a, int[] b) {
        int d = 0;
        for (int j = 0; j < 3; j++) for (int s = 0; s < 12; s += 4) d += Math.abs(((a[j] >> s) & 15) - ((b[j] >> s) & 15));
        return d;
    }

    /** 상대 주 색으로 쓸 수 있나 — 0·1 은 늘 · 프리셋은 그 검질 기본·2P색 둘 다와 ≥ FAR, 앞에 남은 프리셋과 > SAME */
    static boolean usable(int row, int sty, int i) { return row >= 0 && row < 16 && i >= 0 && i <= 15 && USABLE[row][sty & 1][i]; }
    private static final boolean[][][] USABLE = new boolean[16][2][16];
    static {
        for (int row = 0; row < 16; row++) {
            boolean[] kept = new boolean[16];                  /* 프리셋 i 가 앞 프리셋(남은 것)과 겹치지 않나 — 두 검질 같은 값이라 검질과 무관 */
            for (int i = 2; i < 16; i++) {
                kept[i] = true;
                for (int j = 2; j < i; j++) if (kept[j] && dist(tab(row, 0, i), tab(row, 0, j)) <= SAME) kept[i] = false;
            }
            for (int sty = 0; sty < 2; sty++)
                for (int i = 0; i < 16; i++) {
                    int[] t = tab(row, sty, i);
                    USABLE[row][sty][i] = i <= 1 || (kept[i] && dist(t, tab(row, sty, 0)) >= FAR && dist(t, tab(row, sty, 1)) >= FAR);
                }
        }
    }

    /** 정수 HSV(h 0~359 · s·v 0~255) → 12비트 0x0BGR — 기기·JVM·파이썬이 같은 값(정수만) */
    static int hsv12(int h, int s, int v) {
        h = Math.floorMod(h, 360);
        int c = v * s / 255, x = c * (60 - Math.abs((h % 120) - 60)) / 60, m = v - c;
        int r, g, b;
        switch (h / 60) {
            case 0: r = c; g = x; b = 0; break;
            case 1: r = x; g = c; b = 0; break;
            case 2: r = 0; g = c; b = x; break;
            case 3: r = 0; g = x; b = c; break;
            case 4: r = x; g = 0; b = c; break;
            default: r = c; g = 0; b = x; break;
        }
        return (r + m) * 15 / 255 | ((g + m) * 15 / 255) << 4 | ((b + m) * 15 / 255) << 8;
    }
    static String hueName(int h) {
        String n = HUE_NAME[0];
        for (int k = 0; k < HUE_AT.length; k++) if (h >= HUE_AT[k]) n = HUE_NAME[k];
        return n;
    }

    /** 그 사람만의 색 — 12번 시도(못 만들면 null). 피부 = 그 검질 기본 색 1 그대로(얼굴이 이상해지지 않게) */
    static Col unique(int row, int sty, RankCore.Rng r) {
        int[] b0 = tab(row, sty, 0), b1 = tab(row, sty, 1);
        for (int k = 0; k < 12; k++) {
            int h = r.nextInt(360), s = 150 + r.nextInt(90), v = 190 + r.nextInt(66), v3 = 70 + r.nextInt(40);
            int[] t = { b0[0], hsv12(h, s, v), hsv12(h, Math.min(255, s + 40), v3) };
            if (dist(t, b0) < FAR || dist(t, b1) < FAR) continue;
            boolean near = false;
            for (int i = 2; i < 16 && !near; i++) near = dist(t, tab(row, sty, i)) <= SAME;
            if (near) continue;
            return new Col(UNIQUE, t, hueName(h), 0);
        }
        return null;
    }

    /** 이 상대의 컬러(결정론 — 같은 씨앗·같은 id 면 늘 같음). 상대가 될 수 없는 캐릭터(0~14 밖)면 null */
    static Col of(long seed, RankCore.Player p) {
        if (p == null || p.id == null) return null;
        int row = LookTab.row(p.ch), sty = p.sty & 1;
        if (row < 0) return null;
        for (Object[] rv : RIVAL)
            if (rv[0].equals(p.id) && (int) rv[1] == p.ch && (int) rv[2] == sty && usable(row, sty, (int) rv[3]))
                return new Col((int) rv[3], tab(row, sty, (int) rv[3]), Look.NAMES[(int) rv[3]], (int) rv[4]);
        RankCore.Rng r = new RankCore.Rng(RankCore.Rng.mix(seed, p.idHash(), 0xC0105EEDL));
        Col c = null;
        if (r.nextInt(100) < P_UNIQUE) c = unique(row, sty, r);
        if (c == null) {
            boolean fancy = p.baseMmr >= MMR_FANCY;
            int tot = 0;
            for (int i = 0; i < 16; i++) if (usable(row, sty, i)) tot += w(i, fancy);
            int x = r.nextInt(tot), pick = 0;
            for (int i = 0; i < 16; i++) {
                if (!usable(row, sty, i)) continue;
                x -= w(i, fancy);
                if (x < 0) { pick = i; break; }
            }
            c = new Col(pick, tab(row, sty, pick), Look.NAMES[pick], 0);
        }
        int fx = r.nextInt(100) < P_FX ? 1 + r.nextInt(6) : 0;
        return new Col(c.idx, c.t, c.name, fx);
    }
    private static int w(int i, boolean fancy) { return W[i] * (fancy && (i == 9 || i == 10 || i == 15) ? 2 : 1); }

    /** 저장한 col → Col. t 가 세 개의 12비트가 아니면 null(다시 계산할 것) · fx 범위 밖은 0 */
    static Col fromJson(JSONObject j) {
        if (j == null) return null;
        JSONArray a = j.optJSONArray("t");
        if (a == null || a.length() != 3) return null;
        int[] t = new int[3];
        for (int k = 0; k < 3; k++) {
            Object o = a.opt(k);
            if (!(o instanceof Number)) return null;
            double d = ((Number) o).doubleValue();
            if (d != Math.rint(d) || d < 0 || d > 0xFFF) return null;
            t[k] = (int) d;
        }
        int fx = j.optInt("fx", 0);
        if (fx < 0 || fx >= Look.NFX) fx = 0;
        int idx = j.optInt("i", UNIQUE);
        return new Col(idx, t, j.optString("n", ""), fx);
    }
